async function main() {
  console.log("Fetching reasoning subtest…");
  const { data: subtest, error } = await supabase
    .from("subtests")
    .select("id, topics(id, slug)")
    .eq("slug", "reasoning")
    .single();

  if (error || !subtest) {
    console.error("Failed to fetch subtest:", error?.message);
    process.exit(1);
  }

  const topics = subtest.topics as { id: string; slug: string }[];
  const topicMap = new Map(topics.map((t) => [t.slug, t.id]));

  console.log("Topics found:", [...topicMap.keys()]);

  const TOPIC_QUESTIONS: [string, Q[]][] = [
    ["logic", LOGIC],
    ["numerical", NUMERICAL],
    ["verbal", VERBAL],
    ["data-analysis", DATA_ANALYSIS],
    ["visual-pattern", VISUAL_PATTERN],
    ["abstract-reasoning", ABSTRACT_REASONING],
  ];

  for (const [slug, questions] of TOPIC_QUESTIONS) {
    const topicId = topicMap.get(slug);
    if (!topicId) {
      console.error(`Topic not found: ${slug}`);
      continue;
    }
    await seedTopic(slug, questions, topicId);
  }

  console.log("\nDone! 120 Reasoning questions seeded.");
}

main().catch(console.error);
