import { createClient } from "@supabase/supabase-js";
import * as dotenv from "dotenv";
import * as path from "path";

dotenv.config({ path: path.resolve(__dirname, "../.env.local") });

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!
);

interface Q {
  question_text: string;
  choice_a: string;
  choice_b: string;
  choice_c: string;
  choice_d: string;
  correct_choice: "a" | "b" | "c" | "d";
  explanation: string;
  difficulty: number;
}

async function seedTopic(slug: string, questions: Q[], topicId: string) {
  console.log(`\nSeeding ${questions.length} questions for topic: ${slug} (${topicId})`);
  const rows = questions.map((q) => ({
    topic_id: topicId,
    question_text: q.question_text,
    choice_a: q.choice_a,
    choice_b: q.choice_b,
    choice_c: q.choice_c,
    choice_d: q.choice_d,
    correct_choice: q.correct_choice,
    explanation: q.explanation,
    difficulty: q.difficulty,
    status: "approved",
    is_premium: true,
  }));
  const { error } = await supabase.from("questions").insert(rows);
  if (error) { console.error(`  Error seeding ${slug}:`, error.message); return; }
  console.log(`  Inserted ${rows.length} questions.`);
}

