// ─── MAIN ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log("Starting seed: Reading Comprehension + Reasoning");

  // 1. Get subtest IDs for RC and Reasoning
  const { data: subtestRows, error: subtestFetchErr } = await supabase
    .from("subtests")
    .select("id, slug")
    .in("slug", ["reading-comprehension", "reasoning"]);

  if (subtestFetchErr) { console.error(subtestFetchErr.message); process.exit(1); }

  const subtestIdMap = new Map((subtestRows ?? []).map((s: { id: string; slug: string }) => [s.slug, s.id]));

  // 2. Get all topic IDs for those subtests
  const subtestIds = [...subtestIdMap.values()];
  let topicIds: string[] = [];
  if (subtestIds.length > 0) {
    const { data: topicRows } = await supabase
      .from("topics")
      .select("id")
      .in("subtest_id", subtestIds);
    topicIds = (topicRows ?? []).map((t: { id: string }) => t.id);
  }

  // 3. Delete existing questions and passages for these topics
  if (topicIds.length > 0) {
    // Fetch question IDs first so we can delete dependent session_answers
    const { data: questionRows } = await supabase
      .from("questions")
      .select("id")
      .in("topic_id", topicIds);
    const questionIds = (questionRows ?? []).map((q: { id: string }) => q.id);

    if (questionIds.length > 0) {
      const { error: saErr } = await supabase.from("session_answers").delete().in("question_id", questionIds);
      if (saErr) { console.error("Delete session_answers error:", saErr.message); process.exit(1); }
    }

    const { error: qErr } = await supabase.from("questions").delete().in("topic_id", topicIds);
    if (qErr) { console.error("Delete questions error:", qErr.message); process.exit(1); }
    const { error: pErr } = await supabase.from("passages").delete().in("topic_id", topicIds);
    if (pErr) { console.error("Delete passages error:", pErr.message); process.exit(1); }
    console.log(`Deleted existing questions and passages for ${topicIds.length} topics.`);
  }

  // 4. Seed each subtest
  for (const subtest of [RC, REASONING]) {
    // Upsert subtest
    const { data: subtestRow, error: sErr } = await supabase
      .from("subtests")
      .upsert({
        slug: subtest.slug, name: subtest.name, description: subtest.description,
        display_order: subtest.display_order, exam_type: subtest.exam_type,
        upcat_item_count: subtest.upcat_item_count, mock_item_count: subtest.mock_item_count,
      }, { onConflict: "slug" })
      .select("id")
      .single();
    if (sErr || !subtestRow) { console.error("Subtest upsert error:", sErr?.message); process.exit(1); }

    for (const topic of subtest.topics) {
      // Upsert topic
      const { data: topicRow, error: tErr } = await supabase
        .from("topics")
        .upsert({
          subtest_id: subtestRow.id, slug: topic.slug, name: topic.name,
          description: topic.description, display_order: topic.display_order,
        }, { onConflict: "subtest_id,slug" })
        .select("id")
        .single();
      if (tErr || !topicRow) { console.error("Topic upsert error:", tErr?.message); process.exit(1); }

      // Insert passage groups
      for (const pg of topic.passageGroups) {
        const { data: passageRow, error: pgErr } = await supabase
          .from("passages")
          .insert({ topic_id: topicRow.id, content: pg.content, image_url: pg.image_url })
          .select("id")
          .single();
        if (pgErr || !passageRow) { console.error("Passage insert error:", pgErr?.message); process.exit(1); }

        const qRows = pg.questions.map((q) => ({
          topic_id: topicRow.id, passage_id: passageRow.id, passage_order: q.passage_order,
          question_text: q.question_text, choice_a: q.choice_a, choice_b: q.choice_b,
          choice_c: q.choice_c, choice_d: q.choice_d, correct_choice: q.correct_choice,
          explanation: q.explanation, difficulty: q.difficulty, status: "approved" as const,
        }));
        const { error: qInsErr } = await supabase.from("questions").insert(qRows);
        if (qInsErr) { console.error("Question insert error:", qInsErr.message); process.exit(1); }
      }

      // Insert standalone questions
      if (topic.standalone && topic.standalone.length > 0) {
        const soloRows = topic.standalone.map((q) => ({
          topic_id: topicRow.id, passage_id: null, passage_order: null,
          question_text: q.question_text, choice_a: q.choice_a, choice_b: q.choice_b,
          choice_c: q.choice_c, choice_d: q.choice_d, correct_choice: q.correct_choice,
          explanation: q.explanation, difficulty: q.difficulty, status: "approved" as const,
        }));
        const { error: soloErr } = await supabase.from("questions").insert(soloRows);
        if (soloErr) { console.error("Standalone insert error:", soloErr.message); process.exit(1); }
      }

      const totalQ = topic.passageGroups.reduce((s, pg) => s + pg.questions.length, 0) + (topic.standalone?.length ?? 0);
      console.log(`  ✓ ${subtest.slug} / ${topic.slug}: ${totalQ} questions`);
    }
  }

  console.log("Done.");
}

main().catch(console.error);
